export const getProductImageUrl = (
  productId?: string,
  customImage?: string,
  category?: string
): string => {
  if (
    customImage &&
    (customImage.startsWith('data:') ||
      customImage.startsWith('http://') ||
      customImage.startsWith('https://') ||
      customImage.startsWith('/images/'))
  ) {
    return customImage;
  }
  if (productId && PRODUCT_IMAGE_MAP[productId]) {
    return PRODUCT_IMAGE_MAP[productId];
  }
  if (customImage && PRODUCT_IMAGE_MAP[customImage]) {
    return PRODUCT_IMAGE_MAP[customImage];
  }
  if (category && CATEGORY_IMAGE_MAP[category]) {
    return CATEGORY_IMAGE_MAP[category];
  }
  return '/images/products/banana-chips.jpg';
};
